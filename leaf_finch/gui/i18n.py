def tr(language: str, key: str, **kwargs) -> str:
    lang = language if language in _TEXT else "en"
    template = _TEXT[lang].get(key, _TEXT["en"].get(key, key))
    return template.format(**kwargs)


def translate_runtime_message(text: str, language: str) -> str:
    if language != "pl":
        return text

    replacements = (
        (r"^Using (.+)$", r"Używane urządzenie: \1"),
        (r"^Numerics: real=torch\.float32, complex=torch\.complex64, device=(.+)$", r"Obliczenia: rzeczywiste=torch.float32, zespolone=torch.complex64, urządzenie=\1"),
        (r"^Loaded model (.+) \(optimizer continuation\)$", r"Wczytano model \1 (kontynuacja optymalizatora)"),
        (r"^Loaded model (.+) \(weights-only initialization\)$", r"Wczytano model \1 (inicjalizacja tylko z wag)"),
        (r"^Writing results to (.+)$", r"Zapisywanie wyników do \1"),
        (r"^Saved model checkpoint after epoch ([\d,]+): (.+)$", r"Zapisano checkpoint modelu po epoce \1: \2"),
        (r"^Skipping reconstruction because a stop-after-current-epoch request was received\.$", r"Pominięto rekonstrukcję, ponieważ zażądano zatrzymania po bieżącej epoce."),
        (r"^Starting a new optimizer run from loaded model weights$", r"Uruchamianie nowej optymalizacji od wag wczytanego modelu"),
        (r"^Continuing model from epoch ([\d,]+); target total epochs: ([\d,]+)$", r"Kontynuacja modelu od epoki \1; docelowa łączna liczba epok: \2"),
        (r"^Optimization pixel chunk: ([\d,]+) active DMD pixels$", r"Porcja pikseli optymalizacji: \1 aktywnych pikseli DMD"),
        (r"^Checkpoint already contains ([\d,]+) completed epochs; increase target total epochs above ([\d,]+) to continue\.$", r"Checkpoint zawiera już \1 ukończonych epok; aby kontynuować, zwiększ docelową liczbę epok powyżej \2."),
        (r"^Out of memory: reducing pixel chunk ([\d,]+) -> ([\d,]+)$", r"Brak pamięci: zmniejszanie porcji pikseli \1 -> \2"),
        (r"^Stop requested: optimization ended cleanly after epoch ([\d,]+)\.$", r"Zażądano zatrzymania: optymalizacja zakończyła się poprawnie po epoce \1."),
        (r"^Generated ([\d,]+) deterministic FZP patterns$", r"Wygenerowano \1 deterministycznych wzorców FZP"),
        (r"^Reconstruction chunks: points=([\d,]+), pixels=([\d,]+)$", r"Porcje rekonstrukcji: punkty=\1, piksele=\2"),
        (r"^Complete reconstruction field does not fit on the accelerator; using a CPU accumulation buffer\.$", r"Pełne pole rekonstrukcji nie mieści się w pamięci akceleratora; używany jest bufor akumulacyjny CPU."),
        (r"^Reconstruction accumulation buffer: (.+), dtype=(.+)$", r"Bufor akumulacyjny rekonstrukcji: \1, typ danych=\2"),
        (r"^Reconstruction OOM: chunks ([\d,]+)x([\d,]+) -> ([\d,]+)x([\d,]+)$", r"Brak pamięci podczas rekonstrukcji: porcje \1x\2 -> \3x\4"),
        (r"^Checkpoint was created on a different backend; model and Adam state were restored, but stochastic disk sampling restarts from the configured seed\.$", r"Checkpoint utworzono na innym backendzie; model i stan Adama przywrócono, ale losowe próbkowanie obszaru kołowego rozpoczyna się ponownie od skonfigurowanego ziarna."),
    )
    for pattern, replacement in replacements:
        if re.match(pattern, text):
            return re.sub(pattern, replacement, text)

    match = re.match(
        r"^epoch=\s*(\d+)/(\d+) loss=([^ ]+) shape=([^ ]+) mode=([^ ]+) bin=([^ ]+) chunk=([\d,]+)$",
        text,
    )
    if match:
        epoch, total, loss, shape, mode, binary, chunk = match.groups()
        return (
            f"epoka={epoch}/{total} koszt={loss} kształt={shape} "
            f"moc={mode} binaryzacja={binary} porcja={chunk}"
        )
    return text
